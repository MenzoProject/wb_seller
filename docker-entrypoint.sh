#!/bin/sh
# Entrypoint контейнера бота: перед запуском приложения гарантированно
# приводит схему базы данных к актуальному состоянию, применяя все
# ещё не применённые миграции Alembic. Это исключает человеческий
# фактор (забытую вручную команду "alembic upgrade head" при деплое)
# и делает контейнер самодостаточным.

set -e
export PYTHONPATH=/app

echo "[entrypoint] Применение миграций базы данных..."
alembic upgrade head

echo "[entrypoint] Миграции применены. Запуск бота..."
exec python -m src.main
