"""Интерфейс репозитория для работы с пользователями."""

from __future__ import annotations

from typing import Protocol

from src.domain.entities.user import User


class UserRepository(Protocol):
    """Абстракция доступа к данным пользователей, не зависящая от СУБД."""

    async def get_by_id(self, user_id: int) -> User | None:
        """Возвращает пользователя по внутреннему идентификатору.

        Args:
            user_id: Внутренний идентификатор пользователя.

        Returns:
            Найденный пользователь либо None, если пользователь не существует.
        """

    async def get_by_telegram_id(self, telegram_id: int) -> User | None:
        """Возвращает пользователя по идентификатору Telegram.

        Args:
            telegram_id: Уникальный идентификатор пользователя в Telegram.

        Returns:
            Найденный пользователь либо None, если пользователь не зарегистрирован.
        """

    async def create(self, user: User) -> User:
        """Создаёт нового пользователя в хранилище данных.

        Args:
            user: Доменная сущность пользователя без присвоенного `id`.

        Returns:
            Созданный пользователь с присвоенным внутренним идентификатором.
        """

    async def update(self, user: User) -> User:
        """Обновляет данные существующего пользователя.

        Args:
            user: Доменная сущность пользователя с заполненным `id`.

        Returns:
            Обновлённая сущность пользователя.

        Raises:
            EntityNotFoundError: Если пользователь с указанным `id` не найден.
        """

    async def list_all(self, limit: int = 100, offset: int = 0) -> list[User]:
        """Возвращает страницу списка всех зарегистрированных пользователей.

        Args:
            limit: Максимальное количество пользователей в результате.
            offset: Количество пользователей, которые нужно пропустить.

        Returns:
            Список пользователей, упорядоченный по внутреннему идентификатору.
        """

    async def count_all(self) -> int:
        """Возвращает общее количество зарегистрированных пользователей.

        Returns:
            Количество записей в таблице пользователей.
        """
