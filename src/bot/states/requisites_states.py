"""FSM-состояния процесса сохранения платёжных реквизитов пользователя.

Один и тот же набор состояний используется в двух сценариях: при
самостоятельном добавлении реквизитов через раздел «💳 Реквизиты» и при
их указании прямо в процессе оформления заявки (после подтверждения
получения товара). Сценарии различаются наличием ключа `application_id`
в данных FSM: если он присутствует, после сохранения реквизитов
процесс оформления заявки продолжается автоматически.
"""

from __future__ import annotations

from aiogram.fsm.state import State, StatesGroup


class RequisitesStates(StatesGroup):
    """Состояния FSM в процессе сохранения набора реквизитов.

    Attributes:
        waiting_full_name: Ожидание ФИО получателя выплаты.
        waiting_phone: Ожидание номера телефона получателя.
        waiting_bank: Ожидание выбора банка из инлайн-клавиатуры.
    """

    waiting_full_name = State()
    waiting_phone = State()
    waiting_bank = State()
