"""Роли пользователя в системе."""

from __future__ import annotations

import enum


class UserRole(str, enum.Enum):
    """Роль участника, взаимодействующего с ботом.

    Используется middleware разграничения доступа для определения того,
    какое меню и какие обработчики должны быть доступны пользователю.

    Attributes:
        USER: Обычный пользователь-реселлер.
        ADMIN: Администратор с доступом к панели управления.
        SUPER_ADMIN: Администратор с расширенными правами (управление
            остальными администраторами, критичные настройки).
    """

    USER = "USER"
    ADMIN = "ADMIN"
    SUPER_ADMIN = "SUPER_ADMIN"
