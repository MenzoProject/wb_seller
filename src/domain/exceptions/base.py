"""Базовые классы исключений доменного слоя.

Все доменные исключения наследуются от `DomainError`, что позволяет
верхним слоям (сервисам, хендлерам бота) единообразно перехватывать
и обрабатывать ошибки бизнес-логики, отличая их от технических сбоев
инфраструктуры (сети, базы данных и т.д.).
"""

from __future__ import annotations


class DomainError(Exception):
    """Базовое исключение для всех ошибок доменного слоя.

    Attributes:
        message: Человекочитаемое описание ошибки на русском языке,
            пригодное для показа пользователю или администратору.
    """

    def __init__(self, message: str) -> None:
        """Инициализирует доменное исключение с человекочитаемым сообщением.

        Args:
            message: Текст ошибки.
        """
        super().__init__(message)
        self.message = message


class EntityNotFoundError(DomainError):
    """Исключение, сигнализирующее об отсутствии запрашиваемой сущности.

    Attributes:
        entity_name: Человекочитаемое название типа сущности (например, 'Товар').
        entity_id: Идентификатор сущности, которая не была найдена.
    """

    def __init__(self, entity_name: str, entity_id: int | str) -> None:
        """Инициализирует исключение отсутствия сущности.

        Args:
            entity_name: Человекочитаемое название типа сущности.
            entity_id: Идентификатор искомой сущности.
        """
        super().__init__(f"{entity_name} с id={entity_id} не найден(а)")
        self.entity_name = entity_name
        self.entity_id = entity_id
